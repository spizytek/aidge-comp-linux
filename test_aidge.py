# Every file generated by this script is written under this folder so that the
# workspace itself stays clean.
OUTPUT_DIR = Path(__file__).resolve().parent / "output"

def output_path(filename):
    return str(OUTPUT_DIR / filename)


@contextlib.contextmanager
def working_directory(path):
    """Run from `path` temporarily (Aidge writes some files to the cwd)."""
    previous = Path.cwd()
    os.chdir(path)
    try:
        yield
    finally:
        os.chdir(previous)


def print_environment():
    # Show which backends are registered for the Conv2D operator.
    print(f"Available backends:\n{aidge_core.get_keys_Conv2DOp()}")

    # Restrict logs to Notice and above to keep the output readable.
    aidge_core.Log.set_console_level(aidge_core.Level.Notice)

    # The Conv2D operator is supported but only the "export_serialize" backend is available.
    # This backend allow to generate C++ code but not to run inference.
    # For this we would need "cpu" backend.
    print(f"Available backends:\n{aidge_core.get_keys_Conv2DOp()}")

    # note: Tensor is a special case as 'cpu' backend is provided in the core
    # module to guarantee basic functionalities such as data access
    print(f"Available backends for Tensor:\n{aidge_core.Tensor.get_available_backends()}")


def download_assets():
    # Download the model, input and output data files
    base_url = "https://gitlab.eclipse.org/eclipse/aidge/aidge/-/raw/main/examples/tutorials/101_first_step/"
    files_to_download = ["MLP_MNIST.onnx", "input_digit.npy", "output_digit.npy"]

    for file_name in files_to_download:
        aidge_core.utils.download_file(
            file_path=output_path(file_name), file_url=f"{base_url}{file_name}"
        )


def build_model():
    # Load the ONNX graph.
    
    model = aidge_onnx.load_onnx(output_path("MLP_MNIST.onnx"))

    # Use the remove_flatten recipe
    aidge_core.remove_flatten(model)
    return model


def analyze_model(model):
    # Static analysis can be applied to a graph at any time to assess its
    # complexity in terms of memory usage and computational operations.

    # Dimensions must be forwarded for static analysis!
    model.forward_dims(dims=[[1, 1, 28, 28]], allow_data_dependency=True)

    model_stats = aidge_core.static_analysis.StaticAnalysis(model)
    model_stats.summary()
    model_stats.log_nb_ops_by_type(output_path("stats_ops.png"), log_scale=True)


def load_input_tensors():
    # To perform an inference pass, an image from the MNIST dataset is loaded using numpy.
    digit = np.load(output_path("input_digit.npy"))
    plt.imshow(digit[0][0], cmap="gray")

    output_model = np.load(output_path("output_digit.npy"))
    print(output_model)

    input_tensor = aidge_core.Tensor(digit)
    input_tensor.to_backend("cpu")
    input_tensor.set_data_format(aidge_core.dformat.nchw)
    input_tensor.to_dtype(aidge_core.dtype.float32)
    print(f"Aidge Input Tensor dimensions: \n{input_tensor.dims}")
    return input_tensor, output_model


def run_inference(model, input_tensor, output_model):
    # Currently, the model has no implementation and serves only as a data structure.
    # To set an implementation, a data type and backend must be specified.

    # Configure the model
    model.compile("cpu", aidge_core.dtype.float32, dims=[[1, 1, 28, 28]])
    # it is equivalent to set_datatype(), set_backend() and forward_dims()

    # aidge_core.check_graph_validity(model, report=True)

    # Create scheduler
    scheduler = aidge_core.SequentialScheduler(model)

    # Run inference!
    scheduler.forward(data=[input_tensor])
    # Assert results
    for outNode in model.get_output_nodes():
        output_aidge = np.array(outNode.get_operator().get_output(0))
        print(output_aidge)
        print("Aidge prediction = ", np.argmax(output_aidge[0]))
        assert np.allclose(output_aidge, output_model, rtol=1e-04)

    scheduler.save_scheduling_diagram(output_path("schedulingSequential"))
    # tuto_utils.visualize_mmd(output_path("schedulingSequential_forward.mmd"))


def build_calibration_tensors():
    # Optional: if not using git-lfs, download data stored in the PTQ tutorial
    base_url = "https://gitlab.eclipse.org/eclipse/aidge/aidge/-/raw/main/examples/tutorials/PTQ_tutorial/"
    file_name = "mnist_samples.npy.gz"

    aidge_core.utils.download_file(
        file_path=output_path(file_name), file_url=f"{base_url}{file_name}"
    )

    import gzip

    NB_SAMPLES = 100  # Number of samples to use for PTQ

    # Load data from the PTQ tutorial, either downloaded manually or via git-lfs
    path = next(
        p
        for p in [
            output_path(file_name),
            "../PTQ_tutorial/mnist_samples.npy.gz",
        ]
        if os.path.exists(p)
    )
    samples = np.load(gzip.GzipFile(path, "r"))

    for i in range(10):
        plt.subplot(1, 10, i + 1)
        plt.axis("off")
        plt.tight_layout()
        plt.imshow(samples[i], cmap="gray")

    tensors = []
    for sample in samples[0:NB_SAMPLES]:
        sample = np.reshape(sample, (1, 1, 28, 28)).astype(np.float32)
        tensor = aidge_core.Tensor(sample)
        tensors.append(tensor)
    return tensors


def quantize_model(model, tensors):
    import aidge_quantization

    # Work on a clone so the original float model stays intact.
    quantized_model = model.clone()

    # Set the precision
    aidge_quantization.auto_assign_node_precision(
        graphview=quantized_model,
        act_precision=aidge_core.dtype.int8,
        weight_precision=aidge_core.dtype.int8,
        bias_precision=aidge_core.dtype.int32,
    )

    aidge_quantization.quantize_network(
        network=quantized_model,
        calibration_set=tensors,
        clipping_mode=aidge_quantization.Clipping.MSE,
        no_quant=False,
        optimize_signs=False,
        single_shift=False,
    )
    import aidge_model_explorer
    # aidge_model_explorer.visualize(quantized_model, "MLP_MNIST_quantized", embed=True)
    return quantized_model


def export_model(model, input_tensor):
    import aidge_export_cpp
    from aidge_core.export_utils import (
        compile_export,
        export,
    )
    from aidge_core.export_utils.config import ExportConfig

    from aidge_core.hw_model import get_target_by_name

    target = get_target_by_name("host")
    print(target.lib)

    export_folder = output_path("my_export")
    export_config = ExportConfig(
        target="host",
        export_folder=export_folder,
        dtype="float32",
        dformat="nhwc",
        heuristic="nb_op",
        cuda=False,
        clone_model=False,
    )

    aidge_core.check_graph_validity(model, report=True)

    # Aidge writes some files relative to the cwd (e.g. exported_graph.mmd),
    # so run the export from the output folder.
    with working_directory(OUTPUT_DIR):
        artifact = export(
            graph=model,
            config=export_config,
            input_tensors=[input_tensor],
        )

        artifact = export(
            graph=model,
            config=export_config,
            input_tensors=[input_tensor],
        )

    compile_export(export_folder)

    # Execute the export
    # !./output/my_export/build/run_export


def main():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    print(f"Outputs will be written to: {OUTPUT_DIR}")

    print_environment()
    download_assets()
    model = build_model()
    analyze_model(model)
    input_tensor, output_model = load_input_tensors()
    run_inference(model, input_tensor, output_model)
    tensors = build_calibration_tensors()
    quantized_model = quantize_model(model, tensors)
    export_model(model, input_tensor)


if __name__ == "__main__":
    main()

